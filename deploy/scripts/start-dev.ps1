<#
.SYNOPSIS
    Idempotent MusicHub Enterprise developer bootstrap.

.DESCRIPTION
    Prepares and starts the local development stack:
      1. Resolves the .NET 10 SDK (portable SDK under %LOCALAPPDATA%\Microsoft\dotnet).
      2. Ensures storage\dev.secrets.ps1 exists (gitignored) with strong random secrets.
      3. Starts PostgreSQL 17 from tools\pgsql (detached, survives the shell).
      4. Applies EF Core migrations with `dotnet ef database update`.
      5. Builds the solution when needed and starts MusicHub.Api + MusicHub.Worker detached.
      6. Waits for API health and the worker heartbeat.

    Safe to run repeatedly: running components are detected and left alone unless -Force is used.
    Never prints secrets. Never exposes the API beyond 127.0.0.1 unless ASPNETCORE_URLS says so.

.PARAMETER ApiPort
    Override the API port. Default: from ASPNETCORE_URLS / MUSICHUB_BASE_URL, else the port recorded
    by a previous install step, else the first free port from 5080 upward.

.PARAMETER LanAddress
    Override the address other devices should use. Default: detected at install time and confirmed
    with the operator.

.PARAMETER NonInteractive
    Accept the detected address and the first free port without asking. For CI and automation.

.PARAMETER BindLan
    Listen on the LAN address instead of loopback only, so phones and other devices can reach the
    API directly. Without this switch the API binds 127.0.0.1 and the printed LAN URL will not
    answer.

.PARAMETER SkipDatabase
    Do not start PostgreSQL or apply migrations.

.PARAMETER SkipBuild
    Do not run `dotnet build` (fails fast if the host assemblies are missing).

.PARAMETER SkipWorker
    Do not start MusicHub.Worker.

.PARAMETER Force
    Restart API/Worker even when they are already running. Does not drop the database.

.PARAMETER RegenerateSecrets
    Back up and regenerate storage\dev.secrets.ps1. Refuses to regenerate when the local
    PostgreSQL data directory already exists unless -SkipDatabase is supplied (the existing
    database password would be lost).

.PARAMETER AdminConnection
    Administrator (superuser) connection string used to rotate the developer role password on a
    cluster that already exists. The installer needs it because the superuser password of an
    existing cluster is not stored anywhere. When it is omitted and the cluster already exists,
    start-dev stops with instructions instead of guessing. It is passed to MusicHub.Install through
    the MUSICHUB_PG_ADMIN_CONNECTION environment variable, never on a command line.

.EXAMPLE
    .\deploy\scripts\start-dev.ps1

.EXAMPLE
    .\deploy\scripts\start-dev.ps1 -Force -ApiPort 5080

.EXAMPLE
    .\deploy\scripts\start-dev.ps1 -AdminConnection 'Host=127.0.0.1;Port=5433;Database=postgres;Username=postgres;Password=...'
#>
[CmdletBinding()]
param(
    [int]$ApiPort = 0,
    [string]$LanAddress = '',
    [switch]$NonInteractive,
    [switch]$BindLan,
    [switch]$SkipDatabase,
    [switch]$SkipBuild,
    [switch]$SkipWorker,
    [switch]$Force,
    [switch]$RegenerateSecrets,
    [string]$AdminConnection = '',
    [int]$StartupTimeoutSeconds = 120
)

$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'common.ps1')

$repoRoot = Get-MusicHubRepoRoot

function New-MusicHubDevSecrets {
    param(
        [Parameter(Mandatory)][string]$RepoRoot,
        [Parameter(Mandatory)][bool]$DatabaseInitialized,
        [Parameter(Mandatory)][bool]$IncludeDatabasePassword,
        [int]$Port = 5080,
        [string]$BindHost = '127.0.0.1',
        [string]$PublicHost = '127.0.0.1'
    )
    $secretsPath = Join-Path $RepoRoot 'storage\dev.secrets.ps1'
    if ((Test-Path -LiteralPath $secretsPath) -and -not $RegenerateSecrets) { return $secretsPath }
    if ((Test-Path -LiteralPath $secretsPath) -and $RegenerateSecrets) {
        $backup = "$secretsPath.bak-" + (Get-Date -Format 'yyyyMMdd-HHmmss')
        Copy-Item -LiteralPath $secretsPath -Destination $backup -Force
        Write-MusicHubWarning "Existing secrets backed up to $backup"
    }

    $jwtSecret = New-MusicHubRandomSecret -Bytes 64
    $bootstrapToken = New-MusicHubRandomSecret -Bytes 32
    $adminPassword = 'Mh!' + (New-MusicHubRandomSecret -Bytes 24)
    $adminEmail = 'admin@musichub.local'
    $pgBin = Join-Path $RepoRoot 'tools\pgsql\bin'
    $ffBin = ''
    $ffprobeCandidate = Get-ChildItem -Path (Join-Path $RepoRoot 'tools\ffmpeg') -Recurse -Filter 'ffprobe.exe' -ErrorAction SilentlyContinue | Select-Object -First 1
    if ($ffprobeCandidate) { $ffBin = $ffprobeCandidate.DirectoryName }

    $escape = { param($value) ("$value") -replace "'", "''" }
    $lines = @(
        '# MusicHub Enterprise developer secrets.'
        ("# Generated by deploy/scripts/start-dev.ps1 at " + [DateTimeOffset]::UtcNow.ToString('o') + '.')
        '# This file is gitignored. Never commit it, never paste its contents into logs, tickets, reports or chat.'
        '# Re-run deploy/scripts/start-dev.ps1 -RegenerateSecrets to rotate the JWT and bootstrap secrets.'
        ''
        ("`$env:MUSICHUB_JWT_SECRET = '" + (& $escape $jwtSecret) + "'")
        ("`$env:MUSICHUB_BOOTSTRAP_TOKEN = '" + (& $escape $bootstrapToken) + "'")
    )

    # The database password is deliberately NOT written here. The installer stores the application
    # connection string encrypted under <data root>\keys\db-credential.protected, and the API and
    # Worker read it from there through ConnectionStringResolver. Development and production then
    # share one credential path, and the plaintext password exists only inside that encrypted file.
    if ($IncludeDatabasePassword -and -not $DatabaseInitialized) {
        $lines += ''
        $lines += '# The PostgreSQL role password is generated by MusicHub.Install and stored encrypted at'
        $lines += '# keys\db-credential.protected. It is intentionally absent from this file.'
    }

    $lines += @(
        ("`$env:MUSICHUB_DATA_ROOT = '" + (& $escape (Join-Path $RepoRoot 'storage')) + "'")
        ("`$env:MUSICHUB_PG_DATA_DIR = '" + (& $escape (Join-Path $RepoRoot 'storage\postgres-data')) + "'")
        # The public origin must match the address clients actually dial, otherwise Android/desktop
        # pairing QR codes point at a host the phone cannot reach. It is written from the endpoint
        # the operator chose during this install, not from a fixed loopback default.
        ("`$env:MUSICHUB_PUBLIC_URL = 'http://" + $PublicHost + ':' + $Port + "'")
        ("`$env:MUSICHUB_ADMIN_EMAIL = '" + (& $escape $adminEmail) + "'")
        ("`$env:MUSICHUB_ADMIN_PASSWORD = '" + (& $escape $adminPassword) + "'")
        ("`$env:ASPNETCORE_ENVIRONMENT = 'Development'")
        ("`$env:ASPNETCORE_URLS = 'http://" + $BindHost + ':' + $Port + "'")
        # The development stack runs the Telegram bot worker by default now: version 1 makes an
        # install start the Telegram bot automatically on both the Windows and the Docker path, so
        # the generated developer secrets must not silence the polling loop.
        ("`$env:Telegram__WorkerEnabled = 'true'")
        ''
        '# Toolchain'
        ('$env:PATH = "$env:PATH;' + $pgBin + ';' + $ffBin + '"')
    )
    if ($ffBin) {
        $lines += ("`$env:MUSICHUB_FFPROBE_PATH = '" + (& $escape (Join-Path $ffBin 'ffprobe.exe')) + "'")
        $lines += ("`$env:MUSICHUB_FFMPEG_PATH = '" + (& $escape (Join-Path $ffBin 'ffmpeg.exe')) + "'")
    }
    $lines += ''

    New-MusicHubDirectory -Path (Split-Path -Parent $secretsPath) | Out-Null
    Set-Content -LiteralPath $secretsPath -Value $lines -Encoding UTF8
    try {
        & icacls.exe $secretsPath /inheritance:r /grant:r "$($env:USERNAME):(R,W)" 2>&1 | Out-Null
    }
    catch { Write-MusicHubWarning "Could not tighten ACLs on $secretsPath. Restrict it manually to your account." }

    return $secretsPath
}

function Invoke-MusicHubInstallCredential {
    <#
        Provision the developer database role and its encrypted credential through MusicHub.Install,
        which is the same path a native production install uses.

        Two situations have to be distinguished, because they need different credentials:

        * A brand-new cluster: initdb has just created the superuser with a freshly generated
          password, so the superuser credential is loaded from --admin-from-file.
        * An existing cluster (the current developer database): the superuser password is not known
          and must not be invented, so the installer rotates the application role password through
          the administrator connection supplied by -AdminConnection. Without one it refuses rather
          than guessing.
    #>
    param(
        [Parameter(Mandatory)][string]$RepoRoot,
        [Parameter(Mandatory)][string]$DataRoot,
        [Parameter(Mandatory)][string]$Dotnet,
        [Parameter(Mandatory)][bool]$FreshCluster,
        [string]$AdminConnection = ''
    )

    $installCsproj = Join-Path $RepoRoot 'src\server\MusicHub.Install\MusicHub.Install.csproj'
    $installDll = Join-Path $RepoRoot 'src\server\MusicHub.Install\bin\Debug\net10.0\MusicHub.Install.dll'
    if (-not (Test-Path -LiteralPath $installDll)) {
        Write-MusicHubInfo 'Building MusicHub.Install'
        $buildOutput = & $Dotnet build $installCsproj --nologo -v minimal 2>&1
        if ($LASTEXITCODE -ne 0) {
            throw "MusicHub.Install failed to build.`n$((@($buildOutput) | ForEach-Object { "$_" }) -join "`n")"
        }
    }

    $credentialPath = Join-Path $DataRoot 'keys\db-credential.protected'
    $previousErrorAction = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    try {
        if ($FreshCluster) {
            $args = @($installDll, 'create-credential', '--data-root', $DataRoot, '--create-role', '--create-database', '--admin-from-file')
        }
        elseif ([string]::IsNullOrWhiteSpace($AdminConnection)) {
            # An existing cluster with no administrator connection used to be a hard failure. That
            # made the documented install path unusable: `install-server.ps1` creates the cluster and
            # the credential, and the very next step (`start-dev.ps1`) then refused to continue
            # because it could not rotate a password it no longer needed to rotate.
            #
            # The credential file is the authority. If it is present and actually authenticates
            # against the running cluster, there is nothing to provision: reuse it. Verification
            # happens through the installer's own --probe path, so a stale or undecryptable file is
            # still rejected rather than trusted.
            $reusable = $false
            if (Test-Path -LiteralPath $credentialPath) {
                $probe = & $Dotnet $installDll verify-credential --data-root $DataRoot --probe 2>&1
                $reusable = ($LASTEXITCODE -eq 0)
                if ($reusable) {
                    (@($probe) | ForEach-Object { "$_" }) |
                        Where-Object { $_ -match 'Verified|Stored|OK' } |
                        ForEach-Object { Write-MusicHubInfo "$_" }
                    Write-MusicHubInfo "Reusing the existing verified database credential at $credentialPath."
                }
                else {
                    Write-MusicHubWarning 'The existing database credential did not verify; re-provisioning it.'
                }
            }
            if ($reusable) {
                return $credentialPath
            }
            throw "The database cluster at $DataRoot already exists and its superuser password is not known, " +
                  "and no usable credential file was found at $credentialPath. " +
                  "Pass -AdminConnection 'Host=127.0.0.1;Port=5433;Database=postgres;Username=postgres;Password=...' " +
                  "so the installer can rotate the application role password, or point -DataRoot at a fresh directory."
        }
        else {
            $env:MUSICHUB_PG_ADMIN_CONNECTION = $AdminConnection
            $args = @($installDll, 'create-credential', '--data-root', $DataRoot, '--create-role', '--create-database')
        }
        $output = & $Dotnet @args 2>&1
        $exitCode = $LASTEXITCODE
    }
    finally {
        $ErrorActionPreference = $previousErrorAction
        [Environment]::SetEnvironmentVariable('MUSICHUB_PG_ADMIN_CONNECTION', $null, 'Process')
    }

    (@($output) | ForEach-Object { "$_" }) |
        Where-Object { $_ -match 'Wrote|Rotated|Created|Granted|ERROR|Stored' } |
        ForEach-Object { Write-MusicHubInfo "$_" }
    if ($exitCode -ne 0) {
        throw "MusicHub.Install create-credential failed (exit $exitCode). $((@($output) | ForEach-Object { "$_" }) -join ' ')"
    }
    if (-not (Test-Path -LiteralPath $credentialPath)) {
        throw "The installer reported success but no credential file exists at $credentialPath."
    }

    # Prove the stored credential actually works before the API relies on it: this is the same
    # assertion the production installer runs, including the non-superuser and schema checks.
    $verify = & $Dotnet $installDll verify-credential --data-root $DataRoot --probe 2>&1
    $verifyExit = $LASTEXITCODE
    (@($verify) | ForEach-Object { "$_" }) | ForEach-Object { Write-MusicHubInfo "$_" }
    if ($verifyExit -ne 0) {
        throw "The stored database credential failed verification (exit $verifyExit)."
    }
    return $credentialPath
}

function Invoke-MusicHubDotnetEf {
    <# Run dotnet ef with the repository's project layout. #>
    param([Parameter(Mandatory)][string[]]$Arguments)
    $infra = Join-Path $repoRoot 'src\server\MusicHub.Infrastructure\MusicHub.Infrastructure.csproj'
    $api = Join-Path $repoRoot 'src\server\MusicHub.Api\MusicHub.Api.csproj'
    $efArgs = @('ef') + $Arguments + @('--project', $infra, '--startup-project', $api, '--context', 'MusicHubDbContext')
    $previousErrorAction = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    try {
        $output = & (Resolve-MusicHubDotnet) @efArgs 2>&1
        $exitCode = $LASTEXITCODE
    }
    finally { $ErrorActionPreference = $previousErrorAction }
    return [pscustomobject]@{ ExitCode = $exitCode; Text = ((@($output) | ForEach-Object { "$_" }) -join "`n") }
}

function Test-MusicHubDotnetEf {
    <# True when the dotnet-ef command is resolvable (global tool shim on PATH). #>
    $previousErrorAction = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    try { & (Resolve-MusicHubDotnet) 'ef' '--version' 2>&1 | Out-Null; return ($LASTEXITCODE -eq 0) }
    catch { return $false }
    finally { $ErrorActionPreference = $previousErrorAction }
}

function Start-MusicHubPostgresServer {
    <# Start PostgreSQL 17 from the portable distribution with pg_ctl (detached, survives the shell). #>
    param([Parameter(Mandatory)]$Config, [Parameter(Mandatory)][bool]$InitializeIfMissing)
    if (-not $Config.PgCtl) { throw "pg_ctl was not found. Expected tools\pgsql\bin\pg_ctl.exe." }
    if (Test-MusicHubPostgresReady -Config $Config -Quiet) { return 'PostgreSQL already running' }
    New-MusicHubDirectory -Path $Config.PgDataDir | Out-Null
    $versionFile = Join-Path $Config.PgDataDir 'PG_VERSION'
    if (-not (Test-Path -LiteralPath $versionFile)) {
        if (-not $InitializeIfMissing) { throw "PostgreSQL data directory $($Config.PgDataDir) is not initialized and initialisation was disabled." }
        $initdb = Join-Path $Config.PgBin 'initdb.exe'
        if (-not (Test-Path -LiteralPath $initdb)) { throw "initdb.exe not found in $($Config.PgBin)." }
        $existing = Get-ChildItem -LiteralPath $Config.PgDataDir -Force -ErrorAction SilentlyContinue
        if ($existing) { throw "PostgreSQL data directory $($Config.PgDataDir) is not empty but has no PG_VERSION. Refusing to initialise over unknown files." }
        New-MusicHubDirectory -Path $Config.RunDir | Out-Null
        $passwordFile = Join-Path $Config.RunDir 'initdb.pw'
        Set-Content -LiteralPath $passwordFile -Value $Config.Password -Encoding ASCII -NoNewline
        $previousErrorAction = $ErrorActionPreference
        $ErrorActionPreference = 'Continue'
        try {
            # initdb spawns children that inherit its stdout/stderr handles, so calling it directly
            # blocks the pipeline forever. Redirect to files and wait on the process instead.
            $initOut = Join-Path $Config.LogDir 'initdb.out.log'
            $initErr = Join-Path $Config.LogDir 'initdb.err.log'
            New-MusicHubDirectory -Path $Config.LogDir | Out-Null
            $initArgs = '-D "' + $Config.PgDataDir + '" -U "' + $Config.Username + '" --pwfile="' + $passwordFile + '" --auth-local=trust --auth-host=scram-sha-256 -E UTF8 --locale=C'
            $initProcess = Start-Process -FilePath $initdb -ArgumentList $initArgs `
                -RedirectStandardOutput $initOut -RedirectStandardError $initErr -WindowStyle Hidden -PassThru
            $initProcess.WaitForExit(300000) | Out-Null
            $initProcess.Refresh()
            $exitCode = $initProcess.ExitCode
            $output = @()
            foreach ($p in @($initErr, $initOut)) {
                if (Test-Path -LiteralPath $p) { $output += (Get-Content -LiteralPath $p -Raw) }
            }
        }
        finally {
            $ErrorActionPreference = $previousErrorAction
            Remove-Item -LiteralPath $passwordFile -Force -ErrorAction SilentlyContinue
        }
        if (-not (Test-Path -LiteralPath $versionFile)) { throw "initdb failed (exit $exitCode). $((@($output) | ForEach-Object { "$_" }) -join ' ')" }
        Write-MusicHubInfo "Initialised new PostgreSQL cluster at $($Config.PgDataDir)."
    }

    $logFile = Join-Path $Config.LogDir 'postgres.log'
    New-MusicHubDirectory -Path $Config.LogDir | Out-Null
    # Same handle-inheritance problem as initdb: pg_ctl hands its stdout/stderr to the postmaster.
    $pgStartOut = Join-Path $Config.LogDir 'pg-start.out.log'
    $pgStartErr = Join-Path $Config.LogDir 'pg-start.err.log'
    $pgArgs = '-D "' + $Config.PgDataDir + '" -l "' + $logFile + '" -o "-p ' + $Config.Port + ' -c listen_addresses=' + $Config.Host + '" -w -t 60 start'
    $pgCtlProcess = Start-Process -FilePath $Config.PgCtl -ArgumentList $pgArgs `
        -RedirectStandardOutput $pgStartOut -RedirectStandardError $pgStartErr -WindowStyle Hidden -PassThru
    $pgCtlProcess.WaitForExit(90000) | Out-Null
    $pgCtlProcess.Refresh()
    $text = ''
    foreach ($p in @($pgStartErr, $pgStartOut)) {
        if (Test-Path -LiteralPath $p) { $text += (Get-Content -LiteralPath $p -Raw) }
    }
    # Judge by whether the server actually answers rather than by ExitCode, which Start-Process
    # -PassThru does not always refresh.
    if (-not (Test-MusicHubPostgresReady -Config $Config -Quiet)) {
        throw "pg_ctl start failed (exit $($pgCtlProcess.ExitCode)). $text See $logFile."
    }

    $deadline = (Get-Date).AddSeconds(60)
    while ((Get-Date) -lt $deadline) {
        if (Test-MusicHubPostgresReady -Config $Config -Quiet) { return 'PostgreSQL started' }
        Start-Sleep -Milliseconds 500
    }
    throw "PostgreSQL did not become ready within 60 seconds. See $logFile."
}

$config = $null
$exitCode = 0
try {
    Write-Host ''
    Write-Host 'MusicHub Enterprise - developer bootstrap' -ForegroundColor Cyan
    Write-MusicHubInfo "Repository: $repoRoot"

    Write-MusicHubStep '1/7 .NET SDK'
    $dotnet = Initialize-MusicHubDotnet
    # `dotnet --version` is an SDK command. A package install ships a private runtime and no SDK, so
    # the command exits non-zero with a native stderr write, and under $ErrorActionPreference='Stop'
    # (set at the top of this script) PowerShell turns that into a terminating NativeCommandError.
    # The runtime is what the hosts actually need; the SDK is only needed for `dotnet build` and
    # `dotnet ef`, both of which a package install skips. Probe for it instead of requiring it.
    $previousErrorAction = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    try {
        $sdkVersion = ((& $dotnet --version 2>&1) -join ' ').Trim()
        $sdkExit = $LASTEXITCODE
    }
    finally { $ErrorActionPreference = $previousErrorAction }

    if ($sdkExit -eq 0 -and $sdkVersion -match '^10\.') {
        Write-MusicHubInfo "dotnet $sdkVersion"
        $script:sdkAvailable = $true
    }
    elseif ($sdkExit -eq 0) {
        Write-MusicHubWarning "Expected a .NET 10 SDK, found '$sdkVersion'."
        $script:sdkAvailable = $true
    }
    elseif ($SkipBuild) {
        # Expected for a packaged install: a private runtime, published assemblies, no SDK.
        Write-MusicHubInfo "No .NET SDK at $dotnet; using the prebuilt assemblies (-SkipBuild)."
        $script:sdkAvailable = $false
    }
    else {
        throw "No .NET SDK was found at $dotnet, and this run needs one to build the solution. Install the .NET 10 SDK, or install from the Server for Windows package (which ships prebuilt assemblies and a private runtime)."
    }

    Write-MusicHubStep '2/6 Network address and listening port'
    # The address other devices use and the port the API binds are discovered here, before any
    # file that records them is written. Hard-coding either one is what breaks the install on the
    # next machine, and a fixed port collides with whatever else the host already runs.
    $endpoint = Resolve-MusicHubEndpoint `
        -RepoRoot $repoRoot `
        -Port $ApiPort `
        -LanAddress $LanAddress `
        -PreferredPort 5080 `
        -Mode 'windows' `
        -NonInteractive:$NonInteractive `
        -Persist
    $ApiPort = $endpoint.Port
    $bindHost = if ($BindLan -and $endpoint.LanAddress) { '0.0.0.0' } else { '127.0.0.1' }
    $publicHost = if ($BindLan -and $endpoint.LanAddress) { $endpoint.LanAddress } else { '127.0.0.1' }
    Write-MusicHubInfo "LAN address: $($endpoint.LanAddress)"
    Write-MusicHubInfo "Listening port: $ApiPort"
    if (-not $BindLan) {
        Write-MusicHubInfo 'Binding loopback only. Pass -BindLan so phones and other devices can connect.'
    }

    Write-MusicHubStep '3/7 Developer secrets'
    New-MusicHubDirectory -Path (Join-Path $repoRoot 'storage') | Out-Null
    $secretsPath = Join-Path $repoRoot 'storage\dev.secrets.ps1'
    $pgVersionFile = Join-Path $repoRoot 'storage\postgres-data\PG_VERSION'
    $databaseInitialized = Test-Path -LiteralPath $pgVersionFile
    if ((Test-Path -LiteralPath $secretsPath) -and $RegenerateSecrets -and $databaseInitialized -and -not $SkipDatabase) {
        throw "Refusing to regenerate secrets while the local PostgreSQL cluster exists: the stored password would no longer match. Re-run with -SkipDatabase only after you have aligned the database role password."
    }
    if (-not (Test-Path -LiteralPath $secretsPath)) {
        Write-MusicHubWarning 'No storage\dev.secrets.ps1 found. Generating strong random JWT and bootstrap secrets.'
        Write-MusicHubWarning 'The file is gitignored and contains the generated administrator password used by deploy/scripts/verify.ps1 and integrity-scan.ps1.'
        New-MusicHubDevSecrets -RepoRoot $repoRoot -DatabaseInitialized $databaseInitialized -IncludeDatabasePassword (-not $databaseInitialized) -Port $ApiPort -BindHost $bindHost -PublicHost $publicHost | Out-Null
    }
    elseif ($RegenerateSecrets) {
        New-MusicHubDevSecrets -RepoRoot $repoRoot -DatabaseInitialized $databaseInitialized -IncludeDatabasePassword (-not $databaseInitialized) -Port $ApiPort -BindHost $bindHost -PublicHost $publicHost | Out-Null
    }
    $config = Get-MusicHubConfig -RepoRoot $repoRoot
    if (-not $env:MUSICHUB_JWT_SECRET -or $env:MUSICHUB_JWT_SECRET.Length -lt 32) {
        throw "MUSICHUB_JWT_SECRET is missing or shorter than 32 characters. Fix $secretsPath (or re-run with -RegenerateSecrets) and retry."
    }
    if (-not $env:MUSICHUB_DATA_ROOT) { $env:MUSICHUB_DATA_ROOT = $config.DataRoot }

    # The generated secrets file is only a default. An existing file keeps the port it was written
    # with, so the values this run actually uses are forced into the child environment: otherwise a
    # re-run with a new port would start the API on the old one while printing the new URL.
    $env:ASPNETCORE_URLS = "http://${bindHost}:$ApiPort"
    $env:MUSICHUB_PUBLIC_URL = "http://${publicHost}:$ApiPort"
    $config.ApiBaseUrl = "http://${bindHost}:$ApiPort"
    Write-MusicHubInfo "Secrets loaded from $secretsPath (values not printed)."
    Write-MusicHubInfo "Connection target: $($config.Host):$($config.Port)/$($config.Database) as $($config.Username)"
    Write-MusicHubInfo "Data root: $($config.DataRoot)"
    foreach ($directory in @($config.DataRoot, $config.LogDir, $config.RunDir, $config.MusicRoot, $config.ArtworkRoot, $config.QuarantineRoot)) {
        New-MusicHubDirectory -Path $directory | Out-Null
    }

    $apiHealthUrl = "http://127.0.0.1:$ApiPort/healthz"
    $apiDetailUrl = "http://127.0.0.1:$ApiPort/api/health"

    Write-MusicHubStep '4/7 PostgreSQL and the encrypted credential'
    if ($SkipDatabase) {
        Write-MusicHubInfo 'Skipped (-SkipDatabase).'
    }
    else {
        $clusterExistedBefore = Test-Path -LiteralPath (Join-Path $config.PgDataDir 'PG_VERSION')
        $dbState = Start-MusicHubPostgresServer -Config $config -InitializeIfMissing $true
        Write-MusicHubInfo $dbState
        if (-not (Test-MusicHubPostgresReady -Config $config -Quiet)) { throw 'PostgreSQL is not accepting connections.' }
        Write-MusicHubInfo "PostgreSQL ready on $($config.Host):$($config.Port)."

        # Provision the role and its encrypted credential through the same installer a production
        # install uses, so development and production share one credential path instead of
        # development keeping a plaintext password in dev.secrets.ps1.
        $credentialPath = Invoke-MusicHubInstallCredential `
            -RepoRoot $repoRoot `
            -DataRoot $config.DataRoot `
            -Dotnet $dotnet `
            -FreshCluster (-not $clusterExistedBefore) `
            -AdminConnection $AdminConnection
        Write-MusicHubInfo "Encrypted database credential: $credentialPath"

        # The resolver must find the credential and nothing weaker. A leftover plaintext override
        # would silently win over the file, hiding a broken credential, so remove it for the
        # children this script launches.
        if ($env:MUSICHUB_CONNECTION_STRING) {
            Write-MusicHubWarning 'MUSICHUB_CONNECTION_STRING was set and takes precedence over the credential file. Clearing it for this run so the encrypted credential is exercised.'
            [Environment]::SetEnvironmentVariable('MUSICHUB_CONNECTION_STRING', $null, 'Process')
        }
    }

    Write-MusicHubStep '5/7 Build and migrations'
    $needsBuild = -not $SkipBuild
    if ($needsBuild) {
        $buildArgs = @('build', $config.Solution, '--nologo', '-v', 'minimal')
        $previousErrorAction = $ErrorActionPreference
        $ErrorActionPreference = 'Continue'
        try {
            $buildOutput = & $dotnet @buildArgs 2>&1
            $buildExit = $LASTEXITCODE
        }
        finally { $ErrorActionPreference = $previousErrorAction }
        if ($buildExit -ne 0) {
            throw "dotnet build failed (exit $buildExit).`n$((@($buildOutput) | ForEach-Object { "$_" }) -join "`n")"
        }
        Write-MusicHubInfo 'Solution built.'
    }
    elseif (-not (Test-Path -LiteralPath $config.ApiDll)) {
        throw "API assembly missing at $($config.ApiDll) and -SkipBuild was supplied."
    }

    if (-not $SkipDatabase) {
        if (-not (Test-MusicHubPostgresReady -Config $config -Quiet)) { throw 'Cannot apply migrations: PostgreSQL is not running.' }
        $sourceMigrations = Get-MusicHubMigrationIds -RepoRoot $repoRoot
        $appliedMigrations = Get-MusicHubAppliedMigrations -Config $config
        $sourceLatest = if ($sourceMigrations.Count -gt 0) { $sourceMigrations[-1] } else { '' }
        $appliedLatest = if ($appliedMigrations.Count -gt 0) { $appliedMigrations[-1] } else { '' }
        if ($sourceLatest -and $appliedLatest -eq $sourceLatest) {
            Write-MusicHubInfo "Database is up to date ($appliedLatest)."
        }
        else {
            Write-MusicHubInfo "Applying migrations (database current: '$appliedLatest', source latest: '$sourceLatest')."
            $efAvailable = $script:sdkAvailable -and (Test-MusicHubDotnetEf)
            if (-not $efAvailable -and $script:sdkAvailable) {
                Write-MusicHubWarning 'dotnet-ef is not available. Attempting a global tool install (requires network).'
                & $dotnet tool install --global dotnet-ef --version 10.0.0 2>&1 | ForEach-Object { Write-MusicHubInfo "$_" }
                $efAvailable = Test-MusicHubDotnetEf
            }
            if ($efAvailable) {
                $update = Invoke-MusicHubDotnetEf -Arguments @('database', 'update', '--no-build')
                if ($update.ExitCode -ne 0) {
                    Write-MusicHubWarning 'dotnet ef database update --no-build failed; retrying with a full design-time build.'
                    $update = Invoke-MusicHubDotnetEf -Arguments @('database', 'update')
                }
                if ($update.ExitCode -ne 0) { throw "dotnet ef database update failed (exit $($update.ExitCode)).`n$($update.Text)" }
                $appliedMigrations = Get-MusicHubAppliedMigrations -Config $config
                $appliedLatest = if ($appliedMigrations.Count -gt 0) { $appliedMigrations[-1] } else { '' }
                if ($appliedLatest -ne $sourceLatest) {
                    throw "Migrations are still not current after dotnet ef database update (database '$appliedLatest', source '$sourceLatest')."
                }
                Write-MusicHubInfo "Migrations applied: $appliedLatest"
            }
            else {
                # A package install has a private runtime and no SDK, so `dotnet ef` cannot run and a
                # network tool install is not available either. The API applies pending migrations
                # itself on startup when Database:MigrateOnStartup is true, which the package secrets
                # set. Verify that afterwards rather than claiming success here.
                Write-MusicHubInfo 'No dotnet-ef available: the API will apply pending migrations on startup (Database:MigrateOnStartup).'
                if (-not $env:Database__MigrateOnStartup) { $env:Database__MigrateOnStartup = 'true' }
            }
        }
    }

    Write-MusicHubStep '6/7 API'
    $apiProcesses = @(Get-MusicHubProcesses -Kind 'Api')
    $apiListening = Test-MusicHubTcpPort -Port $ApiPort
    if ($Force -and $apiProcesses.Count -gt 0) {
        foreach ($process in $apiProcesses) {
            Write-MusicHubInfo "Stopping API process $($process.ProcessId) (-Force)."
            Stop-MusicHubHostProcess -ProcessId $process.ProcessId | Out-Null
        }
        Remove-MusicHubPidFile -Config $config -Kind 'Api'
        $apiProcesses = @()
        $apiListening = Test-MusicHubTcpPort -Port $ApiPort
    }
    if ($apiListening) {
        Write-MusicHubInfo "API already listening on http://127.0.0.1:$ApiPort - leaving it running."
    }
    elseif ($apiProcesses.Count -gt 0) {
        Write-MusicHubWarning "Found $($apiProcesses.Count) MusicHub.Api process(es) that are not listening on port $ApiPort. Stopping them before starting a healthy instance."
        foreach ($process in $apiProcesses) { Stop-MusicHubHostProcess -ProcessId $process.ProcessId | Out-Null }
        Remove-MusicHubPidFile -Config $config -Kind 'Api'
    }
    if (-not $apiListening) {
        $apiPid = Start-MusicHubHostProcess -Config $config -Kind 'Api' -DllPath $config.ApiDll -WorkingDirectory $config.ApiProjectDir
        Write-MusicHubInfo "Started MusicHub.Api (PID $apiPid)."
    }
    if (-not (Wait-MusicHubHttp -Url $apiHealthUrl -TimeoutSeconds $StartupTimeoutSeconds)) {
        $errLog = Join-Path $config.LogDir 'api.err.log'
        $tail = if (Test-Path -LiteralPath $errLog) { (Get-Content -LiteralPath $errLog -Tail 20) -join "`n" } else { 'no error log found' }
        throw "API did not become healthy at $apiHealthUrl within $StartupTimeoutSeconds seconds.`n$tail"
    }
    Write-MusicHubInfo "API healthy: $apiHealthUrl"

    Write-MusicHubStep '7/7 Worker'
    if ($SkipWorker) {
        Write-MusicHubInfo 'Skipped (-SkipWorker).'
    }
    else {
        $workerProcesses = @(Get-MusicHubProcesses -Kind 'Worker')
        if ($Force -and $workerProcesses.Count -gt 0) {
            foreach ($process in $workerProcesses) {
                Write-MusicHubInfo "Stopping worker process $($process.ProcessId) (-Force)."
                Stop-MusicHubHostProcess -ProcessId $process.ProcessId | Out-Null
            }
            Remove-MusicHubPidFile -Config $config -Kind 'Worker'
            $workerProcesses = @()
        }
        if ($workerProcesses.Count -gt 0) {
            Write-MusicHubInfo "Worker already running (PID $($workerProcesses[0].ProcessId)) - leaving it running."
        }
        else {
            $workerPid = Start-MusicHubHostProcess -Config $config -Kind 'Worker' -DllPath $config.WorkerDll -WorkingDirectory $config.WorkerProjectDir
            Write-MusicHubInfo "Started MusicHub.Worker (PID $workerPid)."
        }
        $credFile = Join-Path $config.DataRoot 'keys\db-credential.protected'
        $hasEncryptedCredOnly = (Test-Path -LiteralPath $credFile) -and [string]::IsNullOrWhiteSpace($env:MUSICHUB_CONNECTION_STRING)
        $workerRunning = (Get-MusicHubProcesses -Kind Worker).Count -gt 0

        if ($hasEncryptedCredOnly) {
            # In a package install, the database role password is encrypted for the application in db-credential.protected;
            # psql does not have the plaintext password. Process presence confirms the worker is active.
            if ($workerRunning) {
                $pidToShow = if ($workerProcesses -and $workerProcesses.Count -gt 0) { $workerProcesses[0].ProcessId } else { $workerPid }
                Write-MusicHubInfo "Worker is running (PID $pidToShow)."
            }
        }
        else {
            $deadline = (Get-Date).AddSeconds(30)
            $heartbeat = $null
            while ((Get-Date) -lt $deadline) {
                $heartbeat = Get-MusicHubWorkerHeartbeat -Config $config
                if ($heartbeat.Present -and $heartbeat.AgeSeconds -le 120) { break }
                Start-Sleep -Seconds 3
            }
            if ($heartbeat.Present -and $heartbeat.AgeSeconds -le 120) {
                Write-MusicHubInfo "Worker heartbeat is current (age $($heartbeat.AgeSeconds)s)."
            }
            elseif ($workerRunning) {
                Write-MusicHubInfo "Worker process is running."
            }
            else {
                Write-MusicHubWarning "Worker heartbeat is not current yet. Check $(Join-Path $config.LogDir 'worker.err.log')."
            }
        }
    }

    Write-MusicHubStep 'Summary'
    $health = Invoke-MusicHubHttp -Url $apiDetailUrl
    Write-MusicHubInfo "API:      $($config.ApiBaseUrl)  /healthz  /api/health  /hubs/library"
    if ($health.StatusCode -eq 200 -and $health.Json) {
        $checks = $health.Json.checks
        Write-MusicHubInfo ("Checks:   database={0} ffprobe={1} storageWritable={2}" -f $checks.database, $checks.ffprobe, $checks.storageWritable)
    }
    Write-MusicHubInfo "Data root: $($config.DataRoot)"
    Write-MusicHubInfo "Logs:     $($config.LogDir)"
    Write-MusicHubInfo 'Next:     .\deploy\scripts\verify.ps1'

    # Print the exact URLs to type. Asking the operator to work out the machine's own address is
    # how a phone ends up configured with the wrong host.
    Write-MusicHubAccessSummary -Port $ApiPort -LanAddress $endpoint.LanAddress -DashboardPath '/index.html'
    if (-not $BindLan) {
        Write-Host '    Note: this run binds loopback only, so the "Other devices" URL will not answer.' -ForegroundColor Yellow
        Write-Host '          Re-run with -BindLan to serve the LAN, then allow the port through the firewall.' -ForegroundColor Yellow
        Write-Host ''
    }
    Write-Host 'Developer stack is running.' -ForegroundColor Green
}
catch {
    $exitCode = 1
    Write-MusicHubError $_.Exception.Message
}
finally {
    if ($config) {
        # Never leave secrets lying in the operator's shell environment longer than necessary.
        [Environment]::SetEnvironmentVariable('PGPASSWORD', $null, 'Process')
    }
}

exit $exitCode
