// Release signing material lives outside the repository (storage/ is gitignored), so the
// keystore and its password can never be committed. When the file is absent - a fresh clone or
// CI without secrets - the release build stays unsigned instead of silently falling back to the
// debug key, which Play Protect blocks on Android 8+.
// rootProject is src/android, so the repository root is two levels up.
val keystorePropertiesFile = rootProject.file("../../storage/android-keys/keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) {
        keystorePropertiesFile.inputStream().use { load(it) }
    }
}
val hasReleaseSigning = keystoreProperties.getProperty("storeFile") != null

